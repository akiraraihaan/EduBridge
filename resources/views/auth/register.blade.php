        function validateEmail() {
            const emailInput = document.getElementById('email');
            const errorElement = document.getElementById('email-error');
            const email = emailInput.value;
            const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

            errorElement.classList.add('hidden');
            emailInput.classList.remove('border-red-500');

            if (!email) {
                errorElement.textContent = 'Email tidak boleh kosong.';
                errorElement.classList.remove('hidden');
                emailInput.classList.add('border-red-500');
                return false;
            }

            if (!emailRegex.test(email)) {
                errorElement.textContent = 'Format email tidak valid.';
                errorElement.classList.remove('hidden');
                emailInput.classList.add('border-red-500');
                return false;
            }

            return true;
        }

        // Tambahkan event listener untuk validasi email
        document.getElementById('email').addEventListener('input', validateEmail);
        document.getElementById('email').addEventListener('blur', validateEmail);

        function submitForm(e) {
            e.preventDefault();
            console.log('Form submission started');

            const form = document.getElementById('registerForm');
            const submitBtn = document.getElementById('submit-btn');
            const btnText = document.getElementById('btn-text');
            const btnLoader = document.getElementById('btn-loader');
            const roleId = document.getElementById('role_id').value;

            // Show loading state
            submitBtn.disabled = true;
            btnText.classList.add('invisible');
            btnLoader.classList.remove('hidden');
            btnLoader.classList.add('flex');

            // Create FormData object
            const formData = new FormData(form);

            // Submit form using fetch
            fetch(form.action, {
                method: 'POST',
                body: formData,
                headers: {
                    'X-CSRF-TOKEN': document.querySelector('input[name="_token"]').value,
                    'Accept': 'application/json'
                }
            })
            .then(response => response.json())
            .then(data => {
                if (data.status === 'success') {
                    // Tampilkan SweetAlert2 sukses
                    Swal.fire({
                        icon: 'success',
                        title: 'Berhasil!',
                        text: 'Akun berhasil dibuat! Silakan login dengan akun Anda.',
                        confirmButtonText: 'OK',
                        confirmButtonColor: '#3085d6',
                        allowOutsideClick: false
                    }).then((result) => {
                        if (result.isConfirmed) {
                            window.location.href = '{{ route('login') }}';
                        }
                    });
                } else if (data.errors && data.errors.email) {
                    // Tampilkan SweetAlert2 untuk email yang sudah terdaftar
                    Swal.fire({
                        icon: 'error',
                        title: 'Oops...',
                        text: data.errors.email[0],
                        confirmButtonColor: '#3085d6'
                    });
                    // Reset loading state
                    submitBtn.disabled = false;
                    btnText.classList.remove('invisible');
                    btnLoader.classList.add('hidden');
                    btnLoader.classList.remove('flex');
                } else {
                    throw new Error('Terjadi kesalahan saat mendaftar');
                }
            })
            .catch(error => {
                console.error('Error:', error);
                // Tampilkan SweetAlert2 untuk error umum
                Swal.fire({
                    icon: 'error',
                    title: 'Oops...',
                    text: error.message,
                    confirmButtonColor: '#3085d6'
                });
                // Reset loading state
                submitBtn.disabled = false;
                btnText.classList.remove('invisible');
                btnLoader.classList.add('hidden');
                btnLoader.classList.remove('flex');
            });
        }

